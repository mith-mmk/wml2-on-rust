//! Evaluation-only ABI for a single-thread Node host; no filesystem or WML2.
use zune_core::bit_depth::BitDepth;
use zune_core::colorspace::ColorSpace;
use zune_core::options::EncoderOptions;
use zune_jpegxl::JxlSimpleEncoder;

#[unsafe(no_mangle)]
pub extern "C" fn probe_alloc(n: usize) -> *mut u8 {
    assert!(n <= 8 << 20);
    Box::into_raw(vec![0u8; n].into_boxed_slice()) as *mut u8
}

/// Caller must provide the live allocation and original length from probe_alloc.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn probe_free(p: *mut u8, n: usize) {
    drop(unsafe { Box::from_raw(std::ptr::slice_from_raw_parts_mut(p, n)) });
}

/// Evaluation-only trusted host ABI. Inputs are generated by the Python runner.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn probe_encode(
    p: *const u8,
    n: usize,
    w: usize,
    h: usize,
    channels: usize,
    bits: usize,
) -> *mut Vec<u8> {
    if !(2..=1024).contains(&w) || !(2..=1024).contains(&h) {
        return std::ptr::null_mut();
    }
    let color = match channels {
        1 => ColorSpace::Luma,
        2 => ColorSpace::LumaA,
        3 => ColorSpace::RGB,
        4 => ColorSpace::RGBA,
        _ => return std::ptr::null_mut(),
    };
    if !matches!(bits, 8 | 16) || n != w * h * channels * (bits / 8) {
        return std::ptr::null_mut();
    }
    let data = unsafe { std::slice::from_raw_parts(p, n) };
    let depth = if bits == 8 {
        BitDepth::Eight
    } else {
        BitDepth::Sixteen
    };
    let options = EncoderOptions::new(w, h, color, depth).set_num_threads(1);
    let mut out = Vec::new();
    match JxlSimpleEncoder::new(data, options).encode(&mut out) {
        Ok(_) => Box::into_raw(Box::new(out)),
        Err(_) => std::ptr::null_mut(),
    }
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn probe_output_ptr(p: *const Vec<u8>) -> *const u8 {
    unsafe { (&*p).as_ptr() }
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn probe_output_len(p: *const Vec<u8>) -> usize {
    unsafe { (&*p).len() }
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn probe_output_free(p: *mut Vec<u8>) {
    drop(unsafe { Box::from_raw(p) });
}
